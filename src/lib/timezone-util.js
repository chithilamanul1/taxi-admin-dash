export function detectLocalTimezone() {
    try {
        const formatter = new Intl.DateTimeFormat('en-US', { timeZoneName: 'short' });
        const parts = formatter.formatToParts(new Date());
        const tzPart = parts.find(p => p.type === 'timeZoneName');
        if (tzPart && tzPart.value) {
            const val = tzPart.value.toUpperCase();
            if (WORLD_TIMEZONES.some(tz => tz.value.toUpperCase() === val)) {
                return val;
            }
        }
        
        const offsetMinutes = -new Date().getTimezoneOffset();
        const sign = offsetMinutes >= 0 ? '+' : '-';
        const absMinutes = Math.abs(offsetMinutes);
        const hours = Math.floor(absMinutes / 60);
        const mins = absMinutes % 60;
        const offsetStr = `UTC${sign}${hours.toString().padStart(2, '0')}:${mins.toString().padStart(2, '0')}`;
        
        if (WORLD_TIMEZONES.some(tz => tz.value === offsetStr)) {
            return offsetStr;
        }
        
        const offsetStrSimple = `UTC${sign}${hours}:${mins.toString().padStart(2, '0')}`;
        const matchedTz = WORLD_TIMEZONES.find(tz => 
            tz.label.includes(offsetStr) || 
            tz.label.includes(offsetStrSimple)
        );
        if (matchedTz) {
            return matchedTz.value;
        }
        
        return offsetStr;
    } catch (e) {
        return 'SLST';
    }
}

export function parseStoredTime(timeStr) {
    if (!timeStr) return { time24h: "12:00", time12h: "12:00 PM", timezone: 'SLST' };
    
    const parts = timeStr.trim().split(/\s+/);
    const timePart = parts[0];
    if (!timePart || !timePart.includes(':')) {
        return { time24h: "12:00", time12h: "12:00 PM", timezone: 'SLST' };
    }
    
    let [hStr, mStr] = timePart.split(':');
    let hour = parseInt(hStr, 10) || 0;
    let minute = parseInt(mStr, 10) || 0;
    
    let period = '';
    let timezone = 'SLST';
    
    if (parts[1]) {
        const pUpper = parts[1].toUpperCase();
        if (pUpper === 'AM' || pUpper === 'PM') {
            period = pUpper;
            if (parts[2]) {
                timezone = parts[2];
            }
        } else {
            timezone = parts[1];
        }
    }
    
    if (period) {
        if (period === 'PM' && hour < 12) hour += 12;
        if (period === 'AM' && hour === 12) hour = 0;
    }
    
    const time24h = `${hour.toString().padStart(2, '0')}:${minute.toString().padStart(2, '0')}`;
    
    const hour12 = hour % 12 === 0 ? 12 : hour % 12;
    const finalPeriod = hour >= 12 ? 'PM' : 'AM';
    const time12h = `${hour12}:${minute.toString().padStart(2, '0')} ${finalPeriod}`;
    
    return { time24h, time12h, timezone };
}

export function formatStoredTime(slotTime, timezone) {
    if (!slotTime) slotTime = "12:00 PM";
    if (!timezone) timezone = "SLST";
    
    const parts = slotTime.split(' ');
    const timePart = parts[0];
    const period = parts[1];
    
    const [hStr, mStr] = timePart.split(':');
    let hour = parseInt(hStr, 10) || 12;
    const minute = parseInt(mStr, 10) || 0;
    
    const hPad = hour.toString().padStart(2, '0');
    const mPad = minute.toString().padStart(2, '0');
    
    return `${hPad}:${mPad} ${period} ${timezone}`;
}
